// Per-video depth content for the /videos/[slug] pages.
//
// Why this file exists: the video pages carried only an embed + a single intro
// paragraph (~130 unique words each, against ~500 words of site-wide footer), and
// each video is also embedded on its richer defect guide and article. Google
// therefore treated the standalone video URLs as thin and consolidated them away
// ("crawled - currently not indexed"). Each entry below adds a checks list and a
// video-specific FAQ so the page stands on its own.
//
// Two rules when adding entries:
//   1. No invented facts - no measurement values, prices or standard numbers that
//      are not already verified in lib/defects.ts, lib/defect-standards.ts or the
//      video's own intro in lib/video-pages.ts. Otherwise write
//      "התקן הישראלי הרלוונטי".
//   2. Videos that share a topic (e.g. the four aluminium videos) must get
//      genuinely different angles here, or the near-duplicate problem returns.

export interface VideoExtra {
  /** What the inspection covers in this specific video. */
  checks: string[]
  /** Video-specific Q&A. Must not repeat the defect guide's FAQ. */
  faq: { question: string; answer: string }[]
}

